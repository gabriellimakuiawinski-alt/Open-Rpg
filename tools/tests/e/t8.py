from lib2 import *
d=seed(); C=ids(9,1)
pgx.admin(f"insert into public.personagens(id,user_id,campanha_id,nome,privada,dados) values ('{ids(5,3)}','{U['J']}','{C}','Segredo do J',true,'{{}}')")
pgx.admin(f"insert into public.personagens(id,user_id,campanha_id,nome,npc,dados) values ('{ids(5,2)}','{U['M']}','{C}','Vilao NPC',true,'{{}}')")
def espera(pg): pg.wait_for_function("document.getElementById('st')&&/conectado|salvo/.test(document.getElementById('st').textContent)",timeout=9000); pg.wait_for_selector('#app .card',timeout=9000)
def opcoes(pg): return pg.locator('#sel option').all_inner_texts()
with sync_playwright() as p:
    b=p.chromium.launch()
    # dono
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']); espera(pg)
    chk("J abre a propria ficha pelo link",'Heroi do J' in pg.locator('#sel').evaluate("e=>e.selectedOptions[0].textContent"))
    chk("J ve as proprias (publica e privada) e nao ve NPC",not any('NPC' in o for o in opcoes(pg)) and len(opcoes(pg))==2,opcoes(pg))
    pg.fill('[data-p=nome]','Heroi Renomeado'); pg.wait_for_timeout(1300)
    chk("renomear grava",pgx.aj(f"select to_jsonb(nome) from public.personagens where id='{d['fJ']}'")=='Heroi Renomeado')
    pg.evaluate("document.querySelectorAll('details.mais').forEach(d=>d.open=true)")
    chk("seletor de campanha so lista campanhas dele",pg.locator('select[data-camp] option').all_inner_texts()==['— nenhuma (só você vê) —','Campanha Teste'])
    pg.evaluate("document.querySelectorAll('details.mais').forEach(d=>d.open=true)"); pg.check('[data-flag=_priv]'); pg.wait_for_timeout(1300)
    chk("marcar privada grava",pgx.aj(f"select to_jsonb(privada) from public.personagens where id='{d['fJ']}'")==True)
    chk("dono nao ve a caixa NPC",pg.locator('[data-flag=_npc]').count()==0)
    pg.evaluate("document.querySelectorAll('details.mais').forEach(d=>d.open=true)"); pg.select_option('select[data-camp]',''); pg.wait_for_timeout(1300)
    chk("tirar da campanha grava",pgx.aj(f"select to_jsonb(campanha_id is null) from public.personagens where id='{d['fJ']}'")==True)
    chk("e solta o token ligado",pgx.aj(f"select to_jsonb(personagem_id is null) from public.tokens where id='{d['tHeroi']}'")==True)
    pg.evaluate("document.querySelectorAll('details.mais').forEach(d=>d.open=true)"); pg.select_option('select[data-camp]',C); pg.wait_for_timeout(1300)
    pg.evaluate("document.querySelectorAll('details.mais').forEach(d=>d.open=true)"); pg.uncheck('[data-flag=_priv]'); pg.wait_for_timeout(1300)
    chk("voltar para a campanha grava",pgx.aj(f"select to_jsonb(campanha_id) from public.personagens where id='{d['fJ']}'")==C)
    chk("sem erros (dono)",not pg.errs,pg.errs); pg.context.close()
    # outro jogador: leitura
    pg=abre_pg(b,'K','ficha.html?id='+d['fJ']); espera(pg)
    chk("K ve a ficha publica do J, nao a privada",len(opcoes(pg))==1 and not any('Segredo' in o for o in opcoes(pg)),opcoes(pg))
    chk("K: ficha do J em somente leitura",pg.locator('#app fieldset[disabled]').count()==1 and 'Somente leitura' in pg.inner_text('#app'))
    chk("K: nao pode excluir ficha alheia",pg.locator('[data-act=delf]').is_disabled())
    chk("K: sem seletor de campanha nem flags",pg.locator('select[data-camp]').count()==0 and pg.locator('[data-flag]').count()==0)
    chk("sem erros (K)",not pg.errs,pg.errs); pg.context.close()
    # admin
    pg=abre_pg(b,'A','ficha.html?id='+d['fJ']); espera(pg)
    chk("admin edita ficha publica ('admin da campanha')",pg.locator('#app fieldset[disabled]').count()==0 and 'admin da campanha' in pg.inner_text('#app'))
    chk("admin nao ve privada nem NPC",len(opcoes(pg))==1,opcoes(pg))
    pg.fill('[data-p=nome]','Revisado pelo admin'); pg.wait_for_timeout(1300)
    chk("admin grava na ficha do J",pgx.aj(f"select to_jsonb(nome) from public.personagens where id='{d['fJ']}'")=='Revisado pelo admin')
    chk("sem erros (admin)",not pg.errs,pg.errs); pg.context.close()
    # mestre
    pg=abre_pg(b,'M','ficha.html'); espera(pg)
    o=opcoes(pg); chk("mestre ve publica, privada e NPC",len(o)==3,o)
    pg.select_option('#sel',ids(5,2)); pg.wait_for_timeout(300)
    chk("mestre ve a caixa NPC marcada",pg.locator('[data-flag=_npc]').is_checked())
    pg.select_option('#sel',ids(5,3)); pg.wait_for_timeout(300)
    pg.fill('[data-p=nome]','Segredo (revisado)'); pg.wait_for_timeout(1300)
    chk("mestre edita ficha privada",pgx.aj(f"select to_jsonb(nome) from public.personagens where id='{ids(5,3)}'")=='Segredo (revisado)')
    chk("sem erros (mestre)",not pg.errs,pg.errs); pg.context.close()
    # sem parametros: abre direto e cria exemplo para conta sem fichas
    pg=abre_pg(b,'X','ficha.html'); espera(pg)
    chk("conta sem fichas recebe a ficha de exemplo",opcoes(pg)==['Agente Exemplo'] or 'Agente Exemplo' in opcoes(pg)[0],opcoes(pg))
    chk("link de volta ao inicio",pg.locator('a[href="index.html"]').count()==1)
    pg.screenshot(path="/tmp/open-rpg-shots/f_leitura.png")
    b.close()
report()
