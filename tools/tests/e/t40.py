# itens: etiquetas de resumo (dano, alcance, efeito…) no catálogo e no inventário; amaldiçoado com descrição exposta
from lib2 import *
d=seed()
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2000);ev=pg.evaluate
    pg.click('[data-tab=g]');pg.evaluate("document.querySelectorAll('details.mais').forEach(d=>d.open=true)");pg.fill('[data-p="op.pp"]','200');pg.press('[data-p="op.pp"]','Tab');pg.wait_for_timeout(400)
    pg.click('[data-tab=i]');pg.click('[data-act="op-cat"]');pg.wait_for_timeout(500)
    pg.click('#md [data-ab="explosivo"]');pg.wait_for_timeout(300)
    t=pg.inner_text('#md').lower()
    chk("granada de fragmentação mostra dano e área sem ler a descrição",'8d6 perfuração' in t and 'raio de 6m' in t and 'reflexos dt agi' in t)
    chk("granada não repete a descrição longa",'empunhe e gaste ação padrão' not in t)
    pg.click('#md [data-ab="arma"]');pg.wait_for_timeout(300)
    t=pg.inner_text('#md').lower()
    chk("arma mostra dano, crítico, alcance e teste",'dano' in t and 'crítico' in t and 'teste' in t and 'pontaria' in t)
    pg.click('#md [data-ab="protecao"]');pg.wait_for_timeout(300)
    chk("proteção mostra defesa e resistência",'defesa' in pg.inner_text('#md').lower() and 'resistência' in pg.inner_text('#md').lower())
    pg.click('#md [data-ab="modificacao"]');pg.wait_for_timeout(300)
    t=pg.inner_text('#md').lower()
    chk("modificação mostra efeito e onde vale",'efeito' in t and 'vale em' in t)
    pg.click('#md [data-ab="amaldicoado"]');pg.wait_for_timeout(300)
    chk("amaldiçoado: descrição exposta em bloco grande",pg.locator('#md .fxbig').count()==28 and pg.locator('#md .fx:has-text("Elemento")').count()==28)
    pg.screenshot(path='/tmp/c_amal.png')
    pg.click('#md [data-ab="explosivo"]');pg.wait_for_timeout(200);pg.screenshot(path='/tmp/c_expl.png')
    pg.locator('#md .cat-i:has-text("fragmentação")').click();pg.wait_for_timeout(400)
    chk("granada no inventário mostra etiquetas",pg.locator('.op-it .fx:has-text("8d6")').count()==1)
    pg.click('[data-act="op-cat"]');pg.wait_for_timeout(300);pg.click('#md [data-ab="amaldicoado"]');pg.locator('#md .cat-i').first.click();pg.wait_for_timeout(400)
    chk("amaldiçoado no inventário mostra a descrição exposta",pg.locator('.op-it .fxbig').count()==1)
    pg.screenshot(path='/tmp/c_inv.png',full_page=True)
    chk("sem erros",not pg.errs,pg.errs)
    b.close()
report()
