# ficha de monstro: visual próprio, PV, rolagens e vínculo com token
from lib2 import *
d=seed()
CID=ids(9,1)
with sync_playwright() as p:
    b=p.chromium.launch()
    pm=abre_pg(b,'M','inimigos.html');pm.wait_for_timeout(2500)
    pm.click('.abas [data-t="livro"]');pm.wait_for_timeout(400);pm.fill('#q','minotauro');pm.wait_for_timeout(300)
    pm.locator('.en').first.click();pm.wait_for_timeout(300);pm.click('[data-a="usar"]');pm.wait_for_timeout(600)
    pm.fill('#uq','1');pm.click('[data-a="ok"]');pm.wait_for_timeout(1500)
    fid=q("select to_jsonb(id) from public.personagens where nome like 'Minotauro%%' and npc limit 1")
    pf=abre_pg(b,'M','ficha.html?id='+fid);pf.wait_for_timeout(2500)
    chk("ficha de monstro aparece",pf.locator('.mon').count()==1 and pf.locator('.mon-nome').input_value().startswith('Minotauro'))
    chk("só abas Monstro e Notas",pf.locator('#tabs button').count()==2)
    chk("mostra Defesa 44, elemento e VD",'44' in pf.inner_text('.mon') and 'Sangue' in pf.inner_text('.mon') and '280' in pf.inner_text('.mon'),pf.inner_text('.mon')[:200])
    chk("mostra ataques e habilidades",pf.locator('.mon-atq').count()==2 and pf.locator('.mon-hab').count()>=1)
    chk("resistências aparecem",'resist' in pf.inner_text('.mon').lower())
    pf.locator('[data-act="mon-atk"]').first.click();pf.wait_for_timeout(300)
    chk("rolar ataque mostra resultado",'Chifres' in pf.inner_text('#toast') or 'Chifres' in pf.inner_text('body'))
    pf.locator('[data-act="mon-dano"]').first.click();pf.wait_for_timeout(300)
    pf.locator('.mon-pv [data-d="-10"]').first.click();pf.wait_for_timeout(300)
    cur=pf.evaluate("curF().stats.find(s=>s.id=='pv').cur")
    chk("PV caiu 10",cur==740,cur)
    pf.screenshot(path='/tmp/mon1.png',full_page=True)
    pf.locator('.mt:has-text("Fortitude")').click();pf.wait_for_timeout(200)
    pf.click('#tabs [data-tab="n"]');pf.wait_for_timeout(300)
    chk("aba Notas abre",pf.locator('.mon').count()==0)
    chk("agente comum segue com 6 abas",True)
    pj=abre_pg(b,'M','ficha.html?id='+d['fJ']);pj.wait_for_timeout(2000)
    chk("ficha comum não vira monstro",pj.locator('.mon').count()==0 and pj.locator('#tabs button').count()==6)
    chk("sem erros",not pf.errs and not pj.errs,(pf.errs,pj.errs))
    b.close()
report()
