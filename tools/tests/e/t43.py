# Search For Light: ficha automática (classe, origem, marcos, escolhas, rolagens, crítico, poder, Infecção, catálogo)
from lib2 import *
d=seed()
camp=ids(9,1)
pgx.admin(f"update public.campanhas set sistema='sfl', config='{{\"moeda\":\"€\"}}'::jsonb where id='{camp}'")
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2200)
    chk("sem erros ao abrir",not pg.errs,pg.errs)
    chk("sistema da ficha = sfl",pg.evaluate("sisDe(curF())")=='sfl')
    chk("abas do SFL",pg.locator('#tabs button').all_inner_texts()==['Ficha','Combate','Perícias','Inventário','Habilidades','Notas'],pg.locator('#tabs button').all_inner_texts())
    chk("atributos COR/REF/MEN/PRE",pg.evaluate("curF().attrs.map(a=>a.id).join()")=='cor,ref,men,pre')
    chk("15 perícias",pg.evaluate("curF().skills.length")==15)
    chk("4 barras (Vida, Fôlego, Medo, Infecção)",pg.evaluate("curF().stats.map(s=>s.id).join()")=='pv,pe,medo,inf')
    # classe e origem
    pg.select_option('[data-p="sfl.classe"]','combatente');pg.wait_for_timeout(400)
    pg.select_option('[data-p="sfl.origem"]','militar');pg.wait_for_timeout(400)
    chk("Combatente: Vida 10+Corpo×2+4 (Corpo 1 => 16)",pg.evaluate("curF().stats[0].max")==16,pg.evaluate("curF().stats[0].max"))
    chk("Fôlego 5+Reflexo(1)=6",pg.evaluate("curF().stats[1].max")==6)
    chk("Medo máx 5 e Infecção máx 10",pg.evaluate("[curF().stats[2].max,curF().stats[3].max]")==[5,10])
    chk("Militar treina Tiro e Atletismo",pg.evaluate("['Tiro','Atletismo'].every(n=>curF().skills.find(s=>s.n==n).t==3)"))
    # sobe Corpo para 3: Vida 10+6+4=20
    pg.evaluate("setP(curF(),'attrs.0.v',3);touch(curF());render()");pg.wait_for_timeout(300)
    chk("Corpo 3 => Vida 20",pg.evaluate("curF().stats[0].max")==20,pg.evaluate("curF().stats[0].max"))
    chk("Espaços 5+Corpo=8",pg.evaluate("SIS.sfl.derivar(curF()).slots")==8)
    # marcos: jogador (não mestre) não vê botões de marco; usa a função direto
    pg.evaluate("curF().sfl.marco=2;SFL.calc(curF());render()");pg.wait_for_timeout(300)
    D="SIS.sfl.derivar(curF())"
    chk("marco 2: 1 habilidade de trilha e 1 escolha de marco",pg.evaluate(D+".nTrilha")==1 and pg.evaluate(D+".nEsc")==1,pg.evaluate(D+".nTrilha"))
    pg.evaluate("curF().sfl.trilha='atirador';render()");pg.wait_for_timeout(200)
    pg.click('[data-tab=h]');pg.wait_for_timeout(300)
    t=pg.inner_text('#app')
    chk("trilha: 1ª habilidade liberada (Mão firme) e 2ª travada",'Mão firme' in t and 'Marco 3: ainda não liberada' in t,t[:300])
    # escolha de marco: habilidade da classe
    pg.click('[data-act="sfl-esc"]');pg.wait_for_timeout(300)
    chk("janela de escolha com habilidades do Combatente",pg.locator('#md .cat-i:has-text("Pancada pesada")').count()==1)
    pg.locator('#md .cat-i:has-text("Pancada pesada")').click();pg.wait_for_timeout(400)
    chk("escolha registrada",pg.evaluate("curF().sfl.esc.length")==1 and pg.evaluate(D+".escPend")==0)
    # benefício +1 atributo no marco 4
    pg.evaluate("curF().sfl.marco=4;SFL.calc(curF());render()");pg.wait_for_timeout(300)
    pg.click('[data-act="sfl-esc"]');pg.wait_for_timeout(300);pg.locator('#md .cat-i:has-text("+1 atributo")').click();pg.wait_for_timeout(300)
    pg.locator('#md .cat-i[data-k="ref"]').click();pg.wait_for_timeout(400)
    chk("+1 Reflexo (1 -> 2)",pg.evaluate("curF().attrs[1].v")==2)
    chk("Fôlego sobe com Reflexo (7)",pg.evaluate("curF().stats[1].max")==7,pg.evaluate("curF().stats[1].max"))
    # arma especial inicial
    pg.click('[data-act="sfl-arma"]');pg.wait_for_timeout(300);pg.locator('#md .cat-i[data-k="Arco"]').click();pg.wait_for_timeout(300)
    chk("Arco treinado +3",pg.evaluate("curF().sfl.armas")==[{'f':'Arco','t':3}],pg.evaluate("curF().sfl.armas"))
    # poder
    pg.select_option('[data-p="sfl.linha"]','predador');pg.wait_for_timeout(400)
    chk("marco 4: poder nível 2",pg.evaluate(D+".nivelPoder")==2)
    pg.click('[data-act="sfl-poder"][data-nv="1"]');pg.wait_for_timeout(400)
    chk("Garras custa 1 de Infecção",pg.evaluate("curF().stats[3].cur")==1,pg.evaluate("curF().stats[3].cur"))
    for i in range(3): pg.click('[data-act="sfl-poder"][data-nv="2"]');pg.wait_for_timeout(200)
    chk("Infecção 4 = Inquieto",pg.evaluate(D+".faixa[1]")=='Inquieto',pg.evaluate(D+".faixa[1]"))
    for i in range(2): pg.click('[data-act="sfl-poder"][data-nv="2"]');pg.wait_for_timeout(200)
    chk("Infecção 6 = Instável (teste de Vontade no aviso)",pg.evaluate(D+".faixa[1]")=='Instável' and 'Vontade DT 18' in pg.inner_text('#toast, .toast, body'),pg.evaluate(D+".faixa[1]"))
    # inventário: catálogo
    pg.click('[data-tab=i]');pg.click('[data-act="sfl-cat"]');pg.wait_for_timeout(300)
    chk("catálogo tem armas, armaduras e consumíveis",pg.locator('#md .cat-i').count()>=58,pg.locator('#md .cat-i').count())
    pg.locator('#md .cat-i:has-text("Machado (2 mãos)")').first.click();pg.wait_for_timeout(300)
    pg.click('[data-act="sfl-cat"]');pg.wait_for_timeout(300);pg.locator('#md .cat-i:has-text("Arco curto")').first.click();pg.wait_for_timeout(300)
    pg.click('[data-act="sfl-cat"]');pg.wait_for_timeout(300);pg.locator('#md .cat-i:has-text("Fuzil de assalto")').first.click();pg.wait_for_timeout(300)
    pg.click('[data-act="sfl-cat"]');pg.wait_for_timeout(300);pg.locator('#md .cat-i:has-text("Armadura média")').first.click();pg.wait_for_timeout(300)
    chk("4 itens no inventário",pg.evaluate("curF().inv.items.length")==4)
    pg.locator('.op-it:has(input[value="Armadura média"]) [data-act="sfl-eq"]').click();pg.wait_for_timeout(300)
    chk("armadura equipada reduz 2",pg.evaluate(D+".armadura")==2)
    # ataque
    pg.click('[data-tab=c]');pg.wait_for_timeout(300)
    chk("3 armas na aba Combate",pg.locator('[data-act="sfl-atk"]').count()==3,pg.locator('[data-act="sfl-atk"]').count())
    A="SIS.sfl.ataque(curF(),curF().inv.items[%d])"
    chk("Machado: Corpo 3 dados, bônus Contundente/Cortante, crítico 20×3",pg.evaluate(A%0+".dados")==3 and pg.evaluate(A%0+".crit")=={'m':20,'x':3},pg.evaluate(A%0))
    chk("Arco curto treinado: Reflexo 2 dados, bônus 3, crítico 19×2",pg.evaluate(A%1+".dados")==2 and pg.evaluate(A%1+".bonus")==3 and pg.evaluate(A%1+".crit")=={'m':19,'x':2},pg.evaluate(A%1))
    chk("Fuzil sem treino: −1 dado e sem bônus",pg.evaluate(A%2+".dados")==1 and pg.evaluate(A%2+".bonus")==0 and pg.evaluate(A%2+".treinada")==False,pg.evaluate(A%2))
    # dano do machado: 1d10 (crit => 3d10) + Corpo 3
    r=pg.evaluate("(()=>{const o=[];for(let i=0;i<50;i++){const x=SIS.sfl.danoRolar(curF(),curF().inv.items[0],false),y=SIS.sfl.danoRolar(curF(),curF().inv.items[0],true);o.push([x.r.length,x.corpo,y.r.length,x.soma>=4&&x.soma<=13,y.soma>=6&&y.soma<=33])}return o})()")
    chk("dano: 1 dado normal, 3 dados no crítico, Corpo soma",all(x[0]==1 and x[1]==3 and x[2]==3 and x[3] and x[4] for x in r),r[0])
    # teste sem soma de atributo
    r=pg.evaluate("(()=>{const o=[];for(let i=0;i<300;i++){const t=SIS.sfl.teste(3,0,3);o.push([t.r.length,t.d,t.total])}return o})()")
    chk("teste: 3 dados, total = maior dado + treino (sem atributo)",all(x[0]==3 and x[2]==x[1]+3 for x in r))
    r=pg.evaluate("(()=>{const o=[];for(let i=0;i<300;i++){const t=SIS.sfl.teste(0,0,0);o.push([t.r.length,t.d==Math.min(...t.r)])}return o})()")
    chk("atributo 0: 2 dados, fica o menor",all(x[0]==2 and x[1] for x in r))
    r=pg.evaluate("(()=>{const o=[];for(let i=0;i<100;i++){const t=SIS.sfl.teste(2,1,0);const u=SIS.sfl.teste(2,-1,0);o.push([t.r.length,u.r.length])}return o})()")
    chk("vantagem +1 dado, desvantagem −1",all(x==[3,1] for x in r))
    # botões rolam e mostram resultado
    pg.click('[data-act="sfl-atk"][data-i="1"]');pg.wait_for_timeout(300)
    chk("ataque mostra resultado",'Arco curto' in pg.inner_text('body') and '=' in pg.inner_text('body'))
    pg.click('[data-act="sfl-esq"]');pg.wait_for_timeout(300)
    chk("esquiva gasta 1 Fôlego",pg.evaluate("curF().stats[1].cur")==6,pg.evaluate("curF().stats[1].cur"))
    pg.click('[data-tab=p]');pg.wait_for_timeout(300)
    pg.locator('.sk:has-text("Atletismo") .roll').click();pg.wait_for_timeout(300)
    chk("rolar perícia",'Atletismo' in pg.inner_text('body'))
    chk("sem erros no fim",not pg.errs,pg.errs)
    # troca de classe limpa trilha e perícias
    pg.click('[data-tab=g]');pg.select_option('[data-p="sfl.classe"]','batedor');pg.wait_for_timeout(500)
    chk("trocar de classe zera trilha e escolhas de classe",pg.evaluate("curF().sfl.trilha")=='' and pg.evaluate("curF().sfl.esc.filter(e=>e.k=='hab').length")==0)
    chk("Batedor: Fôlego +2",pg.evaluate(D+".folMax")==5+2+2,pg.evaluate(D+".folMax"))
    b.close()
report()
