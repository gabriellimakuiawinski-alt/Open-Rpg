# editar monstro na ficha + token ao usar inimigo na campanha
from lib2 import *
d=seed()
with sync_playwright() as p:
    b=p.chromium.launch()
    pm=abre_pg(b,'M','inimigos.html');pm.wait_for_timeout(2500)
    pm.click('.abas [data-t="livro"]');pm.wait_for_timeout(400);pm.fill('#q','minotauro');pm.wait_for_timeout(300)
    pm.locator('.en').first.click();pm.wait_for_timeout(300);pm.click('[data-a="usar"]');pm.wait_for_timeout(600)
    opts=pm.locator('#us option').count()
    chk("lista de cenas aparece",opts>=2,opts)
    if opts>=2: pm.select_option('#us',index=1)
    pm.fill('#uq','2');pm.click('[data-a="ok"]');pm.wait_for_timeout(1800)
    n=q("select to_jsonb(count(*)) from public.tokens t join public.personagens p on p.id=t.personagem_id where p.nome like 'Minotauro%%'")
    chk("2 tokens criados",n==2,n)
    ocu=q("select to_jsonb(bool_and(oculto)) from public.tokens t join public.personagens p on p.id=t.personagem_id where p.nome like 'Minotauro%%'")
    chk("tokens escondidos",ocu is True,ocu)
    fid=q("select to_jsonb(id) from public.personagens where nome like 'Minotauro%%' and npc order by nome limit 1")
    pf=abre_pg(b,'M','ficha.html?id='+fid);pf.wait_for_timeout(2500)
    pf.locator('.mon-aj summary').click();pf.wait_for_timeout(200)
    pf.locator('[data-act="mon-add-atq"]').click();pf.wait_for_timeout(300)
    chk("aba segue aberta após adicionar",pf.evaluate("document.querySelector('.mon-aj').open"))
    pf.locator('.mon-ed:has([data-p$="dano"])').last.locator('input').first.fill('Pisão');pf.locator('.mon-ed:has([data-p$="dano"])').last.locator('input').first.dispatch_event('change');pf.wait_for_timeout(300)
    pf.locator('.mon-ed:has([data-p$="dano"])').last.locator('input[data-p$="dano"]').fill('3d6+4 Sangue');pf.locator('.mon-ed:has([data-p$="dano"])').last.locator('input[data-p$="dano"]').dispatch_event('change');pf.wait_for_timeout(300)
    t_=pf.inner_text('#app').lower();chk("novo ataque no cartão",'pisão' in t_ and pf.locator('.mon-atq').count()==3,(t_[-700:],pf.evaluate("curF().inv.items.map(i=>i.n)")))
    pf.locator('[data-act="mon-add-hab"]').click();pf.wait_for_timeout(300)
    h=pf.locator('.mon-ed:has([data-mh])').last
    h.locator('select[data-mh]').select_option('Reação');pf.wait_for_timeout(300)
    h=pf.locator('.mon-ed:has([data-mh])').last
    h.locator('textarea').fill('Contra-ataca.');h.locator('textarea').dispatch_event('change');pf.wait_for_timeout(300)
    chk("habilidade com ação Reação",'reação' in pf.inner_text('#app').lower() and 'contra-ataca' in pf.inner_text('#app').lower())
    pf.fill('[data-mn="Sentidos"]','Faro 9m');pf.dispatch_event('[data-mn="Sentidos"]','change');pf.wait_for_timeout(300)
    chk("sentidos aparecem",'faro 9m' in pf.inner_text('#app').lower())
    pf.locator('[data-act="mon-del-atq"]').last.click();pf.wait_for_timeout(300)
    chk("remover ataque",pf.locator('.mon-atq').count()==2)
    pf.wait_for_timeout(1200)
    chk("sem erros",not pm.errs and not pf.errs,(pm.errs,pf.errs))
    b.close()
report()
