# SaH completo: origens, poderes gerais, trilhas, rituais e paranormais só com o complemento; treino automático;
# classe Sobrevivente pelo livro (trilha Durão); regras opcionais da campanha; bestiário e regras.html com SaH
from lib2 import *
d=seed()
camp=ids(9,1)
def cfg(j): pgx.admin(f"update public.campanhas set config='{j}'::jsonb, sistema='op' where id='{camp}'")
D="SIS.aplicar(curF(),SIS.cfgDe(CAMPS.find(c=>c.id==curF()._camp))).D"
def livro(pg,aba):
    if pg.locator('#md [data-x]').count(): pg.click('#md [data-x]');pg.wait_for_timeout(200)
    pg.click('[data-tab=h]');pg.click('[data-act="op-livro"]');pg.wait_for_timeout(500)
    pg.click(f'#md [data-f="gr:{aba}"]');pg.wait_for_timeout(300)
    return pg.inner_text('#md .catl')
with sync_playwright() as p:
    b=p.chromium.launch()
    cfg('{}')
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2000);ev=pg.evaluate
    t=livro(pg,'origem');chk("sem SaH: origem Astronauta não aparece",'Astronauta' not in t)
    pg.click('#md [data-f="gr:poder"]');pg.wait_for_timeout(300);chk("sem SaH: sem poderes gerais",'Atlético' not in pg.inner_text('#md .catl'))
    pg.close()
    cfg('{"complementos":["sah"],"regrasSah":["vestidos","debilitantes"]}')
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2000);ev=pg.evaluate
    t=livro(pg,'origem');chk("com SaH: 46 origens",pg.locator('#md .cat-i').count()==46,pg.locator('#md .cat-i').count())
    chk("etiqueta SaH nas origens",pg.locator('#md .cat-i .compt').count()==20)
    pv0=ev(D+".pvMax")
    pg.locator('#md .cat-i:has-text("Mergulhador")').click();pg.wait_for_timeout(400)
    chk("Mergulhador: +5 PV automático",ev(D+".pvMax")==pv0+5,(pv0,ev(D+".pvMax")))
    t=livro(pg,'poder');chk("poderes gerais aparecem com título",'Poderes gerais' in t and 'Atlético' in t)
    chk("Artista Marcial não repete para combatente",t.count('Artista Marcial')==1,t.count('Artista Marcial'))
    ev("curF().skills.find(s=>s.n=='Atletismo').t=0")
    dl=ev(D+".desloc")
    pg.locator('#md .cat-i:has-text("Atlético")').click();pg.wait_for_timeout(400)
    chk("Atlético treina Atletismo e +3m",ev("curF().skills.find(s=>s.n=='Atletismo').t")==5 and ev(D+".desloc")==dl+3,(ev("curF().skills.find(s=>s.n=='Atletismo').t"),ev(D+".desloc"),dl))
    ev("curF().skills.find(s=>s.n=='Acrobacia').t=5")
    livro(pg,'poder');pg.locator('#md .cat-i:has-text("Acrobático")').click();pg.wait_for_timeout(400)
    chk("já treinado: +2 automático",ev(D+".per['Acrobacia']")==2,ev(D+".per['Acrobacia']"))
    t=livro(pg,'trilha');chk("trilhas novas de combatente",all(x in t for x in ['Agente Secreto','Caçador','Monstruoso']))
    t=livro(pg,'ritual');chk("16 rituais do SaH",pg.locator('#md .cat-i .compt').count()==16,pg.locator('#md .cat-i .compt').count())
    t=livro(pg,'paranormal');chk("poderes paranormais do SaH",'Aura de Pavor' in t and 'Valer-se do Caos' in t)
    pg.click('#md [data-x]')
    pg.click('[data-tab=c]');pg.wait_for_timeout(300)
    chk("card de regras opcionais da campanha",'regras opcionais da campanha' in pg.inner_text('#app').lower() and 'ferimentos debilitantes' in pg.inner_text('#app').lower())
    # sobrevivente
    pg.click('[data-tab=g]');pg.wait_for_timeout(200)
    pg.select_option('select[data-p="op.classe"]','sobrevivente');pg.wait_for_timeout(500)
    ev("curF().poderes=curF().poderes.filter(p=>!/Mergulhador|Fôlego|Atlético|Acrobático/.test(p.n))");pg.select_option('select[data-p="op.estagio"]','2');pg.wait_for_timeout(500)
    chk("estágio 2: aviso de trilha",pg.locator('[data-act="op-hab"]:has-text("Escolher trilha")').count()==1)
    pv1=ev(D+".pvMax")
    pg.click('[data-act="op-hab"]');pg.wait_for_timeout(500)
    chk("trilhas de sobrevivente",all(x in pg.inner_text('#md') for x in ['Durão','Esperto','Esotérico']),pg.inner_text('#md'))
    pg.locator('#md [data-t="Durão"]').click();pg.wait_for_timeout(400)
    chk("Durão: +4 PV",ev(D+".pvMax")==pv1+4,(pv1,ev(D+".pvMax")))
    pg.select_option('select[data-p="op.estagio"]','3');pg.wait_for_timeout(500)
    pv3=ev(D+".pvMax");chk("estágio 3: Durão dá mais +2",pv3==pv1+2+4+2,(pv1,pv3))
    pg.select_option('select[data-p="op.estagio"]','4');pg.wait_for_timeout(500)
    pg.locator('[data-act="op-hab"]:has-text("trilha")').first.click();pg.wait_for_timeout(500)
    chk("estágio 4: Pancada Forte",'Pancada Forte' in pg.inner_text('#md'),pg.inner_text('#md'))
    chk("sem erros",not pg.errs,pg.errs)
    pg.close()
    # bestiário e regras
    pg=abre_pg(b,'J','inimigos.html');pg.wait_for_timeout(1500)
    pg.click('.abas button[data-t="livro"]');pg.wait_for_timeout(400)
    chk("bestiário: criaturas do SaH com etiqueta",pg.locator('.en .compt').count()==30,pg.locator('.en .compt').count())
    pg.click('#fil [data-f="SaH"]');pg.wait_for_timeout(200);chk("filtro SaH",pg.locator('.en').count()==30)
    pg.close()
    pg=abre_pg(b,'J','regras.html#opcional');pg.wait_for_timeout(1500)
    chk("regras opcionais do SaH",'Evolução por patentes' in pg.inner_text('#lst') and 'Combate narrativo' in pg.inner_text('#lst'))
    pg.click('.abas button[data-t="jogo"]');pg.wait_for_timeout(200)
    chk("novas regras do SaH",'Perseguições' in pg.inner_text('#lst') and 'Efeitos de medo' in pg.inner_text('#lst'))
    chk("sem erros (páginas)",not pg.errs,pg.errs)
    b.close()
report()
