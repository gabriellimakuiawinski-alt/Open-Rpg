# Etapa 6b: aviso de subida de NEX leva às habilidades do livro; trilha obrigatória no NEX 10%
from lib2 import *
d=seed()
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2000);ev=pg.evaluate
    pg.select_option('select[data-p="op.nex"]','10');pg.wait_for_timeout(500)
    chk("NEX 10%: aviso de trilha com botão Escolher trilha",pg.locator('[data-act="op-hab"]:has-text("Escolher trilha")').count()==1)
    chk("sem trilha, o aviso não pode ser dispensado",pg.locator('.av-l:has([data-act="op-hab"]) [data-act="op-dispensa"]').count()==0)
    pg.click('[data-act="op-hab"]');pg.wait_for_timeout(500)
    chk("lista as 5 trilhas do combatente",pg.locator('#md .cat-i').count()==5,pg.locator('#md .cat-i').count())
    pg.locator('#md .cat-i:has-text("Guerreiro")').click();pg.wait_for_timeout(500)
    chk("trilha definida",ev("curF().op.trilha")=='Guerreiro')
    chk("recebe a 1ª habilidade da trilha",ev("curF().poderes.some(p=>p.n=='Técnica Letal')"))
    chk("aviso de trilha some",pg.locator('[data-act="op-hab"]').count()==0)
    # poder (NEX 15)
    pg.select_option('select[data-p="op.nex"]','15');pg.wait_for_timeout(500)
    chk("NEX 15%: botão Escolher poder",pg.locator('[data-act="op-hab"]:has-text("Escolher poder")').count()==1)
    pg.click('[data-act="op-hab"]');pg.wait_for_timeout(500)
    chk("lista os 19 poderes de combatente",pg.locator('#md .cat-i').count()==19,pg.locator('#md .cat-i').count())
    pg.locator('#md .cat-i:has-text("Golpe Pesado")').click();pg.wait_for_timeout(400)
    chk("poder adicionado e aviso some",ev("curF().poderes.some(p=>p.n=='Golpe Pesado')") and pg.locator('[data-act="op-hab"]').count()==0)
    # trilha de novo (NEX 40)
    pg.select_option('select[data-p="op.nex"]','40');pg.wait_for_timeout(500)
    pg.locator('[data-act="op-hab"]:has-text("Ver habilidades da trilha")').click();pg.wait_for_timeout(500)
    chk("NEX 40%: só a habilidade disponível da trilha dele (Revidar)",pg.locator('#md .cat-i').count()==1 and 'Revidar' in pg.locator('#md .cat-i').inner_text(),pg.locator('#md .cat-i').count())
    pg.locator('#md .cat-i').click();pg.wait_for_timeout(400)
    chk("Revidar entrou na ficha",ev("curF().poderes.some(p=>p.n=='Revidar')"))
    # trilha obrigatória sem aviso guardado
    ev("curF().op.trilha='';curF().op.avisos=[];render()");pg.wait_for_timeout(300)
    chk("sem trilha em NEX ≥ 10 aparece o cartão obrigatório",pg.locator('[data-act="op-trilha"]').count()==1)
    pg.click('[data-act="op-trilha"]');pg.wait_for_timeout(400)
    chk("cartão abre a escolha de trilhas",pg.locator('#md .cat-i').count()==5)
    pg.click('#md [data-x]')
    # aba: livro é o padrão, criar fica recolhido
    pg.click('[data-tab=h]');pg.wait_for_timeout(200)
    chk("botão Do livro visível",pg.locator('[data-act="op-livro"]').is_visible())
    chk("criar habilidade própria fica recolhido",not pg.locator('[data-act="op-nova"][data-t="homebrew"]').is_visible())
    chk("sem erros",not pg.errs,pg.errs)
    b.close()
report()
