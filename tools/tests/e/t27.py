# mestre: livre na ficha de NPC; na própria ficha de personagem vale a patente (pedido a si mesmo)
from lib2 import *
d=seed()
CID=ids(9,1)
NPC=ids(5,7);PJ=ids(5,8)
pgx.admin(f"insert into public.personagens(id,user_id,campanha_id,nome,npc,dados) values ('{NPC}','{U['M']}','{CID}','Cultista NPC',true,'{{}}'),('{PJ}','{U['M']}','{CID}','Heroi do Mestre',false,'{{}}')")
def katana_certeira(pg):
    pg.click('[data-tab=i]');pg.click('[data-act="op-cat"]');pg.wait_for_timeout(400)
    pg.fill('#catq','katana');pg.locator('#md .cat-i:has-text("Katana")').click();pg.wait_for_timeout(300)
    pg.locator('.op-it:has(input[value^="Katana"]) [data-act="op-modif"]').click();pg.wait_for_timeout(600)
    pg.locator('#md .cat-i:has-text("Certeira")').click();pg.wait_for_timeout(500)
with sync_playwright() as p:
    b=p.chromium.launch()
    pn=abre_pg(b,'M','ficha.html?id='+NPC);pn.wait_for_timeout(2200)
    katana_certeira(pn)
    chk("NPC: mestre aplica livre, sem pedido",pn.locator('#md [data-env]').count()==0 and pn.evaluate("curF().inv.items.find(i=>i.n=='Katana').mods.some(m=>m.n=='Certeira')"))
    pj=abre_pg(b,'M','ficha.html?id='+PJ);pj.wait_for_timeout(2200)
    katana_certeira(pj)
    chk("própria ficha de personagem: patente vale e oferece pedido",pj.locator('#md [data-env]').count()==1)
    pj.click('#md [data-env]');pj.wait_for_timeout(800)
    chk("pedido do mestre gravado",q("select to_jsonb(count(*)) from public.pedidos where estado='pendente' and autor='%s'"%U['M'])==1)
    pm=abre_pg(b,'M','index.html#/c/'+CID);pm.wait_for_timeout(2500)
    pm.click('[data-t="pedidos"]');pm.wait_for_timeout(400);pm.click('[data-v="aprovado"]');pm.wait_for_timeout(900)
    pj.reload();pj.wait_for_timeout(2500);pj.click('[data-tab=i]');pj.wait_for_timeout(1200)
    chk("depois de aprovar, a ficha aplica",pj.evaluate("curF().inv.items.find(i=>i.n=='Katana').mods.some(m=>m.n=='Certeira')"))
    chk("sem erros",not pn.errs and not pj.errs,(pn.errs,pj.errs))
    b.close()
report()
