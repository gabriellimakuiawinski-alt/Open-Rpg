# botão Modificar: lista tudo que o item aceita; itens comuns e coletes (sem classe do catálogo) também
from lib2 import *
d=seed()
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2000);ev=pg.evaluate
    pg.click('[data-tab=g]');pg.fill('[data-p="op.pp"]','50');pg.press('[data-p="op.pp"]','Tab');pg.wait_for_timeout(400)
    pg.click('[data-tab=i]');pg.click('[data-act="op-cat"]');pg.wait_for_timeout(400)
    pg.fill('#catq','katana');pg.locator('#md .cat-i:has-text("Katana")').click();pg.wait_for_timeout(300)
    ev("""(()=>{const f=curF();f.inv.items.push({id:'x1',n:'Colete tático',tipo:'protecao',catg:1,esp:2,def:5,qtd:1,eq:false},{id:'x2',n:'Lupa velha',tipo:'geral',catg:0,esp:1,qtd:1},{id:'x3',n:'Poção',tipo:'consumivel',catg:0,esp:1,qtd:1});render()})()""")
    pg.wait_for_timeout(300)
    chk("Modificar aparece em arma, colete e item comum, não em consumível",pg.locator('[data-act="op-modif"]').count()==3,pg.locator('[data-act="op-modif"]').count())
    pg.locator('.op-it:has(input[value^="Katana"]) [data-act="op-modif"]').click();pg.wait_for_timeout(700)
    nomes=pg.locator('#md .cat-i b').all_inner_texts()
    chk("arma corpo a corpo: lista as modificações de corpo, de qualquer categoria",all(n in nomes for n in ['Certeira','Cruel','Perigosa','Discreta','Tática']) and 'Silenciador' not in nomes,nomes)
    pg.locator('#md .cat-i:has-text("Cruel")').click();pg.wait_for_timeout(500)
    chk("aplica direto na arma",ev("curF().inv.items.find(i=>i.n=='Katana').mods.some(m=>m.n=='Cruel')"))
    pg.locator('.op-it:has(input[value^="Katana"]) [data-act="op-modif"]').click();pg.wait_for_timeout(500)
    chk("já aplicada fica desligada",pg.locator('#md .cat-i[disabled]:has-text("Cruel")').count()==1)
    pg.click('#md [data-x]')
    pg.locator('.op-it:has(input[value^="Colete"]) [data-act="op-modif"]').click();pg.wait_for_timeout(600)
    nomes=pg.locator('#md .cat-i b').all_inner_texts()
    chk("colete: lista modificações de proteção",'Reforçada' in nomes and 'Blindada' in nomes and 'Cruel' not in nomes,nomes)
    pg.locator('#md .cat-i:has-text("Reforçada")').click();pg.wait_for_timeout(500)
    chk("Reforçada no colete: +2 Defesa, espaço não aumenta",ev("(()=>{const i=curF().inv.items.find(i=>i.n=='Colete tático');return i.def==7&&i.esp==2&&i.mods.length==1})()"))
    pg.locator('.op-it:has(input[value^="Lupa"]) [data-act="op-modif"]').click();pg.wait_for_timeout(600)
    nomes=pg.locator('#md .cat-i b').all_inner_texts()
    chk("item comum: lista modificações de acessório",'Aprimorado' in nomes and 'Função adicional' in nomes,nomes)
    pg.click('#md [data-x]')
    pg.click('[data-tab=c]');pg.wait_for_timeout(300)
    chk("botão Modificar também no card de ataques",pg.locator('.arma [data-act="op-modif"]').count()==1)
    chk("sem erros",not pg.errs,pg.errs)
    b.close()
report()
