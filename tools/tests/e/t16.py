# Etapa 6: habilidades do livro (classe, poderes e trilhas) na ficha de Ordem Paranormal
from lib2 import *
d=seed()
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2000);ev=pg.evaluate
    pg.select_option('select[data-p="op.nex"]','20');pg.wait_for_timeout(400)
    def_0=ev("OP.calc(curF()).D.def")
    pg.click('[data-tab=h]');pg.click('[data-act="op-livro"]');pg.wait_for_timeout(500)
    chk("janela do livro abre",pg.locator('#md .cat-i').count()>0)
    chk("combatente: 20 habilidades de trilha",pg.locator('#md .cat-i').count()==20,pg.locator('#md .cat-i').count())
    pg.click('#md [data-gr="poder"]');pg.wait_for_timeout(200)
    chk("combatente: 19 poderes",pg.locator('#md .cat-i').count()==19,pg.locator('#md .cat-i').count())
    pg.locator('#md .cat-i:has-text("Reflexos Defensivos")').click();pg.wait_for_timeout(400)
    chk("poder entra na ficha com efeito",ev("curF().poderes.some(p=>p.n=='Reflexos Defensivos'&&p.ef.length==2)"))
    chk("Reflexos Defensivos: Defesa +2",ev("OP.calc(curF()).D.def")==def_0+2,ev("OP.calc(curF()).D.def"))
    pv_0=ev("curF().stats[0].max")
    pg.click('[data-act="op-livro"]');pg.wait_for_timeout(300)
    pg.locator('#md .cat-i:has-text("Casca Grossa")').click();pg.wait_for_timeout(400)
    chk("Casca Grossa define a trilha vazia",ev("curF().op.trilha")=='Tropa de Choque',ev("curF().op.trilha"))
    chk("Casca Grossa: +1 PV por 5% de NEX (+4 em NEX 20%)",ev("curF().stats[0].max")==pv_0+4,ev("curF().stats[0].max"))
    pg.click('[data-act="op-livro"]');pg.wait_for_timeout(300)
    pg.locator('#md .cat-i:has-text("Casca Grossa")').click();pg.wait_for_timeout(300)
    chk("não duplica a mesma habilidade",ev("curF().poderes.filter(p=>p.n=='Casca Grossa').length")==1)
    chk("janela segue aberta após tentar duplicar",pg.locator('#md').count()==1)
    pg.click('#md [data-cl="ocultista"]');pg.wait_for_timeout(200)
    chk("ocultista: 20 habilidades de trilha",pg.locator('#md .cat-i').count()==20)
    pg.click('#md [data-gr="classe"]');pg.wait_for_timeout(200)
    chk("ocultista: 9 habilidades de classe",pg.locator('#md .cat-i').count()==9,pg.locator('#md .cat-i').count())
    pg.click('#md [data-x]');pg.wait_for_timeout(200)
    chk("sem erros",not pg.errs,pg.errs)
    b.close()
report()
