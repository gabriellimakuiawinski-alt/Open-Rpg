# Search For Light, livro V1.2: inventário (espaços, bolso, pilhas, prontos, sobrecarga), modificações, quebra, fabricação, consumíveis, parkour, descanso e 30 origens
from lib2 import *
d=seed()
camp=ids(9,1)
pgx.admin(f"update public.campanhas set sistema='sfl', config='{{\"moeda\":\"€\"}}'::jsonb where id='{camp}'")
D="SIS.sfl.derivar(curF())"
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2200)
    chk("sem erros ao abrir",not pg.errs,pg.errs)
    chk("30 origens",pg.evaluate("SIS.sfl.dados.origens.length")==30)
    pg.select_option('[data-p="sfl.classe"]','tecnico');pg.wait_for_timeout(300)
    pg.select_option('[data-p="sfl.origem"]','lutador-clandestino');pg.wait_for_timeout(300)
    chk("origem nova treina Contundente e Intimidação",pg.evaluate("['Contundente','Intimidação'].every(n=>curF().skills.find(s=>s.n==n).t==3)"))
    # espaços: 5 + 3 por Corpo a partir do 2 (+2 Técnico)
    for cor,esp in ((1,7),(2,10),(4,16)):
        pg.evaluate(f"setP(curF(),'attrs.0.v',{cor});SFL.calc(curF())")
        chk(f"Corpo {cor}: {esp} espaços (com +2 do Técnico)",pg.evaluate(D+".slots")==esp,pg.evaluate(D+".slots"))
    pg.evaluate("setP(curF(),'attrs.0.v',2);SFL.calc(curF());render()");pg.wait_for_timeout(200)
    # catálogo com preço e raridade
    chk("catálogo: preço e raridade na arma",pg.evaluate("SIS.sfl.CAT.find(x=>x.n=='Pistola 9 mm').preco")==180 and pg.evaluate("SIS.sfl.CAT.find(x=>x.n=='Pistola 9 mm').rar")=='Incomum')
    add=lambda n,q=1: pg.evaluate(f"SIS.sfl.poeItem(curF(),{n!r},{q});SFL.calc(curF());render()")
    add('Balas de pistola ou revólver',30)
    chk("30 balas = 2 espaços (pilha de 20)",pg.evaluate("SIS.sfl.espItem(curF().inv.items[0])")==2)
    for n in ('Isqueiro','Canivete','Analgésico','Apito','Kit de arrombamento'): add(n)
    chk("5 itens de bolso não ocupam espaço",pg.evaluate(D+".espBolso")==0 and pg.evaluate(D+".bolso")==5,pg.evaluate(D+".bolso"))
    add('Soco inglês')
    chk("6º item de bolso ocupa 1",pg.evaluate(D+".espBolso")==1)
    add('Colete balístico')
    u=pg.evaluate(D+".usado")
    pg.evaluate("curF().inv.items.find(x=>x.n=='Colete balístico').eq=true;SFL.calc(curF())")
    chk("armadura vestida não ocupa espaço",pg.evaluate(D+".usado")==u-2 and pg.evaluate(D+".armadura")==2,[u,pg.evaluate(D+".usado")])
    chk("colete: −3 contra tiro",pg.evaluate(D+".armaduraTiro")==3)
    # mochila
    add('Mochila de trilha')
    chk("mochila adicionada já em uso: +4 espaços",pg.evaluate(D+".slots")==14,pg.evaluate(D+".slots"))
    # sobrecarga
    pg.evaluate("curF().inv.items.find(x=>x.n=='Mochila de trilha').eq=false;SFL.calc(curF())")
    add('Marreta (2 mãos)');add('Escopeta de cano duplo');add('Rifle de caça');add('Taco de madeira')
    chk("sobrecarregado: −3 m",pg.evaluate(D+".sobre")==True and pg.evaluate(D+".excesso")==False and pg.evaluate(D+".mov")==6,[pg.evaluate(D+".usado"),pg.evaluate(D+".slots"),pg.evaluate(D+".mov")])
    chk("sobrecarregado: desvantagem em Parkour e Furtividade",pg.evaluate("SIS.sfl.desvAuto(curF(),"+D+",'Parkour').includes('sobrecarregado')") and pg.evaluate("SIS.sfl.desvAuto(curF(),"+D+",'Furtividade').length")>0)
    add('Motosserra (2 mãos)')
    chk("mais de 3 acima do limite: excesso",pg.evaluate(D+".excesso")==True)
    pg.click('[data-tab=g]');pg.wait_for_timeout(200)
    chk("aviso de excesso na ficha",'não dá para carregar' in pg.inner_text('#app'))
    pg.evaluate("curF().inv.items=curF().inv.items.filter(x=>!/Marreta|Escopeta|Rifle|Motosserra|Taco/.test(x.n));curF().inv.items.find(x=>x.n=='Mochila de trilha').eq=true;SFL.calc(curF());render()")
    chk("sem sobrecarga depois de largar",pg.evaluate(D+".sobre")==False)
    # itens prontos
    add('Machado (2 mãos)');add('Pistola 9 mm');add('Lanterna')
    pg.click('[data-tab=i]');pg.wait_for_timeout(300)
    for n in ('Machado (2 mãos)','Pistola 9 mm','Lanterna'):
        pg.locator(f'.op-it:has(input[value="{n}"]) [data-act="sfl-pronto"]').click();pg.wait_for_timeout(200)
    chk("3 prontos de 2: aviso",pg.evaluate(D+".prontos")==3 and pg.evaluate(D+".prontosMax")==2)
    add('Bolsa de cintura')
    chk("bolsa de cintura: +1 item pronto",pg.evaluate(D+".prontosMax")==3)
    chk("lanterna liga a luz do token (10 m)",pg.evaluate("curF().inv.items.find(x=>x.n=='Lanterna').luz.m")==10)
    # modificações
    for n,q in (('Sucata',5),('Peças',3),('Tecido',3)): add(n,q)
    M="curF().inv.items.findIndex(x=>x.n=='Machado (2 mãos)')"
    i=pg.evaluate(M)
    pg.click('[data-tab=i]');pg.wait_for_timeout(200)
    pg.click(f'[data-act="sfl-mod"][data-i="{i}"]');pg.wait_for_timeout(300)
    chk("Modificar lista Fio afiado e Contrapeso no machado",pg.locator('#md .cat-i[data-k="fio-afiado"]').count()==1 and pg.locator('#md .cat-i[data-k="contrapeso"]').count()==1)
    chk("silenciador não serve no machado",pg.locator('#md .cat-i[data-k="silenciador-improvisado"]').count()==0)
    pg.locator('#md .cat-i[data-k="fio-afiado"]').click();pg.wait_for_timeout(300)
    pg.locator('#md .cat-i[data-k="base"]').click();pg.wait_for_timeout(400)
    chk("Fio afiado instalado e materiais gastos (1 Sucata, 1 Peça)",pg.evaluate(f"curF().inv.items[{M}].mods")==['fio-afiado'] and pg.evaluate("SIS.sfl.temMat(curF(),'Sucata')")==4 and pg.evaluate("SIS.sfl.temMat(curF(),'Peças')")==2)
    chk("Fio afiado: margem 20 vira 19",pg.evaluate(f"SIS.sfl.ataque(curF(),curF().inv.items[{M}]).crit")=={'m':19,'x':3})
    pg.evaluate(f"curF().inv.items[{M}].mods.push('alca-leve');SFL.calc(curF())")
    chk("Alça leve: machado ocupa 1",pg.evaluate(f"SIS.sfl.espItem(curF().inv.items[{M}])")==1)
    chk("limite do machado (pesada) é 3",pg.evaluate(f"SIS.sfl.limiteMods(curF().inv.items[{M}])")==3)
    P="curF().inv.items.find(x=>x.n=='Pistola 9 mm')"
    chk("limite da pistola é 2",pg.evaluate(f"SIS.sfl.limiteMods({P})")==2)
    pg.evaluate(f"{P}.mods=['silenciador-improvisado','mira-luneta-ou-ponto-vermelho']")
    r=pg.evaluate(f"(()=>{{const o=[];for(let i=0;i<40;i++){{const x=SIS.sfl.danoRolar(curF(),{P},false);o.push(x.soma>=0&&x.soma<=7&&x.fixo==-1)}}return o}})()")
    chk("silenciador: −1 de dano",all(r))
    chk("mira: +1 dado só mirando",pg.evaluate(f"SIS.sfl.ataque(curF(),{P},true).dados")==pg.evaluate(f"SIS.sfl.ataque(curF(),{P}).dados")+1)
    # quebra e conserto
    pg.evaluate(f"curF().inv.items[{M}].quebrada=true;SFL.calc(curF());render()")
    pg.click('[data-tab=c]');pg.wait_for_timeout(300)
    chk("arma quebrada mostra Consertar e não ataca",pg.locator(f'[data-act="sfl-conserta"][data-i="{i}"]').count()==1 and pg.locator(f'[data-act="sfl-atk"][data-i="{i}"]').count()==0)
    pg.evaluate("curF().sfl.marco=2;curF().sfl.esc=[{k:'hab',n:'Reparo rápido'}];SFL.calc(curF());render()");pg.wait_for_timeout(200)
    pg.click(f'[data-act="sfl-conserta"][data-i="{i}"]');pg.wait_for_timeout(300)
    chk("Reparo rápido conserta sem teste",pg.evaluate(f"curF().inv.items[{M}].quebrada")==False)
    chk("ataque corpo a corpo pode quebrar; Lenhador não quebra machado",pg.evaluate(f"SIS.sfl.ataque(curF(),curF().inv.items[{M}]).quebra")==True and pg.evaluate(f"(()=>{{const f=curF(),o=f.sfl.origem;f.sfl.origem='lenhador';const q=SIS.sfl.ataque(f,f.inv.items[{M}]).quebra;f.sfl.origem=o;return q}})()")==False)
    chk("punhos do Lutador clandestino: 1d6",pg.evaluate("SIS.sfl.PUNHOS(curF()).arma.dano")=='1d6')
    # fabricação (na base): bandagem com 2 Tecido
    tec=pg.evaluate("SIS.sfl.temMat(curF(),'Tecido')")
    pg.evaluate("Math.random=(()=>0.99)")   # dados altos: passa no teste
    pg.click('[data-tab=i]');pg.wait_for_timeout(200)
    pg.click('[data-act="sfl-fab"]');pg.wait_for_timeout(300)
    pg.locator('#md .cat-i:has-text("Bandagem")').click();pg.wait_for_timeout(300)
    pg.locator('#md .cat-i[data-k="base"]').click();pg.wait_for_timeout(400)
    chk("fabricou 3 bandagens e gastou 2 Tecido",pg.evaluate("SIS.sfl.temMat(curF(),'Bandagem')")==3 and pg.evaluate("SIS.sfl.temMat(curF(),'Tecido')")==tec-2,[pg.evaluate("SIS.sfl.temMat(curF(),'Bandagem')"),pg.evaluate("SIS.sfl.temMat(curF(),'Tecido')")])
    chk("3 bandagens = 1 espaço (pilha de 3)",pg.evaluate("SIS.sfl.espItem(curF().inv.items.find(x=>x.n=='Bandagem'))")==1)
    # usar bandagem: cura
    pg.evaluate("curF().stats[0].cur=3;render()");pg.wait_for_timeout(200)
    bi=pg.evaluate("curF().inv.items.findIndex(x=>x.n=='Bandagem')")
    pg.click('[data-tab=i]');pg.wait_for_timeout(200)
    pg.click(f'[data-act="sfl-usar"][data-i="{bi}"]');pg.wait_for_timeout(400)
    chk("bandagem cura (Medicina passou) e gasta 1",pg.evaluate("curF().stats[0].cur")>3 and pg.evaluate("SIS.sfl.temMat(curF(),'Bandagem')")==2,pg.evaluate("curF().stats[0].cur"))
    # adrenalina e descanso longo
    add('Adrenalina')
    ai=pg.evaluate("curF().inv.items.findIndex(x=>x.n=='Adrenalina')")
    fm=pg.evaluate(D+".folMax")
    pg.evaluate("curF().stats[1].cur=0;render()");pg.click('[data-tab=i]');pg.wait_for_timeout(200)
    pg.click(f'[data-act="sfl-usar"][data-i="{ai}"]');pg.wait_for_timeout(300)
    chk("adrenalina: +3 Fôlego e −1 no máximo",pg.evaluate("curF().stats[1].cur")==3 and pg.evaluate(D+".folMax")==fm-1)
    pg.click('[data-tab=c]');pg.wait_for_timeout(200)
    pg.evaluate("curF().stats[2].cur=3;curF().stats[3].cur=2;render()");pg.wait_for_timeout(200)
    pg.click('[data-act="sfl-desc"][data-t="longo"]');pg.wait_for_timeout(300)
    chk("descanso longo: Medo −2, Infecção −1, Fôlego máximo volta",pg.evaluate("curF().stats[2].cur")==1 and pg.evaluate("curF().stats[3].cur")==1 and pg.evaluate(D+".folMax")==fm,[pg.evaluate("curF().stats[2].cur"),pg.evaluate("curF().stats[3].cur")])
    # parkour em perseguição
    pg.click('[data-act="sfl-pers"][data-d="ini"]');pg.wait_for_timeout(200)
    chk("perseguição começa em Perto (3)",pg.evaluate("curF().sfl.pers")==3)
    pg.click('[data-act="sfl-pk"]');pg.wait_for_timeout(300)
    fo=pg.evaluate("curF().stats[1].cur")
    pg.locator('#md .cat-i:has-text("Saltar entre telhados próximos")').click();pg.wait_for_timeout(400)
    chk("parkour com sucesso: Impulso 1, estágio 4, −1 Fôlego",pg.evaluate("curF().sfl.impulso")==1 and pg.evaluate("curF().sfl.pers")==4 and pg.evaluate("curF().stats[1].cur")==fo-1,[pg.evaluate("curF().sfl.impulso"),pg.evaluate("curF().sfl.pers")])
    chk("Impulso 1: +2 m",pg.evaluate(D+".mov")==11)
    pg.evaluate("Math.random=(()=>0)")   # dados baixos: falha
    pg.click('[data-act="sfl-pk"]');pg.wait_for_timeout(300)
    pg.locator('#md .cat-i:has-text("Saltar entre prédios distantes")').click();pg.wait_for_timeout(400)
    chk("falha grave: Impulso zera e perde estágio",pg.evaluate("curF().sfl.impulso")==0 and pg.evaluate("curF().sfl.pers")==3)
    chk("resultado mostra a consequência",'complicação grave' in pg.inner_text('#toast'))
    pg.click('[data-act="sfl-pers"][data-d="0"]');pg.wait_for_timeout(200)
    chk("terminar perseguição",pg.evaluate("curF().sfl.pers")==0)
    # mochila sem impulso quando sobrecarregado
    pg.evaluate("curF().sfl.bonus.slots=-20;SFL.calc(curF());render()");pg.wait_for_timeout(200)
    chk("sobrecarregado: botão + do Impulso travado",pg.locator('[data-act="sfl-imp"][data-d="1"]').is_disabled())
    pg.evaluate("curF().sfl.bonus.slots=0;SFL.calc(curF());render()")
    # item antigo do catálogo ganha as regras novas
    pg.evaluate("curF().inv.items.push({id:'velho',ref:'sfl:Bandagem',n:'Bandagem',tipo:'consumivel',esp:0.5,qtd:1});SFL.calc(curF())")
    chk("item antigo junta na pilha nova",pg.evaluate("curF().inv.items.filter(x=>x.n=='Bandagem').length")==1 and pg.evaluate("SIS.sfl.temMat(curF(),'Bandagem')")==3)
    pg.evaluate("curF().inv.items.push({id:'m1',n:'Balas de pistola ou revólver',tipo:'municao',esp:1,pilha:20,lote:20,qtd:1,ref:'loja1'});SFL.calc(curF())")
    chk("munição comprada em pilha vira 20 balas",pg.evaluate("SIS.sfl.temMat(curF(),'Balas de pistola')")==50,pg.evaluate("SIS.sfl.temMat(curF(),'Balas de pistola')"))
    pg.wait_for_timeout(1500)
    chk("sem erros no fim",not pg.errs,pg.errs)
    b.close()
report()
