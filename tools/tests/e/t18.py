# Etapa 6c: rituais do livro na aba "Do livro"
from lib2 import *
d=seed()
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2000);ev=pg.evaluate
    pg.click('[data-tab=h]');pg.click('[data-act="op-livro"]');pg.wait_for_timeout(500)
    pg.click('#md [data-f="gr:ritual"]');pg.wait_for_timeout(300)
    n=pg.locator('#md .cat-i').count()
    chk("82 rituais no total",n==82,n)
    pg.click('#md [data-f="ci:1"]');pg.wait_for_timeout(200)
    chk("1º círculo: 26",pg.locator('#md .cat-i').count()==26,pg.locator('#md .cat-i').count())
    pg.click('#md [data-f="el:Sangue"]');pg.wait_for_timeout(200)
    chk("1º círculo de Sangue: 6 + Amaldiçoar Arma (elemento à escolha) = 7",pg.locator('#md .cat-i').count()==7,pg.locator('#md .cat-i').count())
    pg.click('#md [data-f="ci:4"]');pg.wait_for_timeout(200)
    chk("4º círculo de Sangue: 3",pg.locator('#md .cat-i').count()==3,pg.locator('#md .cat-i').count())
    pg.click('#md [data-f="ci:1"]');pg.click('#md [data-f="el:"]');pg.wait_for_timeout(200)
    pg.locator('#md .cat-i:has-text("Armadura de Sangue")').click();pg.wait_for_timeout(400)
    chk("ritual entra na ficha com tipo, círculo, elemento e custo",ev("curF().poderes.some(p=>p.n=='Armadura de Sangue'&&p.tipo=='ritual'&&p.circ==1&&p.el=='Sangue'&&p.pe==1)"))
    chk("descrição traz os parâmetros e a forma discente",ev("(curF().poderes.find(p=>p.n=='Armadura de Sangue')||{}).desc||''").find('Discente')>0)
    pg.click('[data-tab=h]');pg.wait_for_timeout(200)
    chk("aparece na aba Habilidades como ritual de 1º círculo",pg.locator('.op-po.t-ritual').count()>=1)
    pg.click('[data-act="op-livro"]');pg.wait_for_timeout(300)
    pg.click('#md [data-f="gr:ritual"]');pg.wait_for_timeout(300)
    chk("lista marca o ritual como já na ficha",'já na ficha' in pg.locator('#md .cat-i:has-text("Armadura de Sangue")').inner_text())
    pg.click('#md [data-x]')
    chk("sem erros",not pg.errs,pg.errs)
    b.close()
report()
