# Etapa 9b: bestiário do livro — listar, abrir, salvar nos meus, usar na campanha
from lib2 import *
d=seed()
CID=ids(9,1)
with sync_playwright() as p:
    b=p.chromium.launch()
    pm=abre_pg(b,'M','inimigos.html');pm.wait_for_timeout(2500)
    pm.click('.abas [data-t="livro"]');pm.wait_for_timeout(500)
    n=pm.locator('.en').count()
    chk("67 criaturas do livro na lista",n==67,n)
    n=q("select to_jsonb(count(*)) from public.livro_inimigos")
    chk("tabela do livro tem 67",n==67,n)
    pm.fill('#q','minotauro');pm.wait_for_timeout(300)
    chk("busca acha o Minotauro",pm.locator('.en').count()==1)
    pm.locator('.en').first.click();pm.wait_for_timeout(300)
    t=pm.inner_text('#md')
    chk("bloco: PV 750, Chifres e Machado",'750' in t and 'Chifres' in t and 'Machado' in t,t[:300])
    pm.click('[data-a="copiar"]');pm.wait_for_timeout(900)
    chk("copiado para os meus",q("select to_jsonb(count(*)) from public.inimigos where nome='Minotauro' and dono='%s'"%U['M'])==1)
    pm.click('.abas [data-t="livro"]');pm.wait_for_timeout(300);pm.fill('#q','minotauro');pm.wait_for_timeout(300)
    pm.locator('.en').first.click();pm.wait_for_timeout(300)
    pm.click('[data-a="usar"]');pm.wait_for_timeout(700)
    pm.fill('#uq','1');pm.click('[data-a="ok"]');pm.wait_for_timeout(1500)
    st=q("select dados->'stats' from public.personagens where nome like 'Minotauro%%' and npc")
    pv=[s for s in st if s['id']=='pv'][0]
    chk("ficha do Minotauro com PV 750",pv['max']==750,pv)
    fid=q("select to_jsonb(id) from public.personagens where nome like 'Minotauro%%' and npc limit 1")
    pf=abre_pg(b,'M','ficha.html?id='+fid);pf.wait_for_timeout(2500)
    D=pf.evaluate("SIS.derivar(curF(),{})")
    chk("Defesa 44 e deslocamento 12",D['def']==44 and D['desloc']==12,(D['def'],D['desloc']))
    chk("ataque Chifres +30",pf.evaluate("curF().inv.items.some(a=>a.n=='Chifres'&&SIS.armaEf(a).atk==30)"))
    r=pgx.run(U['J'],"update public.livro_inimigos set nome='x' where id=1 returning id")
    chk("ninguém altera o livro",not r.get('data'),r)
    chk("sem erros",not pm.errs and not pf.errs,(pm.errs,pf.errs))
    b.close()
report()
