# Etapa 6e: catálogo de itens e armas do livro
from lib2 import *
d=seed()
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=abre_pg(b,'J','ficha.html?id='+d['fJ']);pg.wait_for_timeout(2000);ev=pg.evaluate
    pg.click('[data-tab=g]');pg.evaluate("document.querySelectorAll('details.mais').forEach(d=>d.open=true)");pg.fill('[data-p="op.pp"]','50');pg.press('[data-p="op.pp"]','Tab');pg.wait_for_timeout(400);pg.wait_for_timeout(300)
    pg.click('[data-tab=i]');pg.wait_for_timeout(200)
    pg.click('[data-act="op-cat"]');pg.wait_for_timeout(500)
    n=pg.locator('#md .cat-i').count()
    chk("aba Armas: 35",n==35,n)
    pg.fill('#catq','katana');pg.wait_for_timeout(200)
    chk("busca acha em todas as abas",pg.locator('#md .cat-i').count()==1)
    pg.locator('#md .cat-i:has-text("Katana")').click();pg.wait_for_timeout(400)
    chk("arma entra com dano, crítico e teste",ev("curF().inv.items.some(i=>i.n=='Katana'&&i.tipo=='arma'&&i.arma.dano=='1d10'&&i.arma.crit=='19'&&i.arma.per=='Luta'&&i.catg==1&&i.esp==2)"))
    pg.click('[data-act="op-cat"]');pg.wait_for_timeout(500)
    abas=pg.locator('#md [data-ab]').all_inner_texts()
    chk("abas do catálogo",all(a in abas for a in ['Armas','Proteções','Munição','Acessórios','Explosivos','Operacionais','Paranormais','Modificações','Outros']),abas)
    for ab,k in [('protecao',3),('municao',6),('acessorio',3),('explosivo',5),('operacional',19),('paranormal',16),('modificacao',23)]:
        pg.click(f'#md [data-ab="{ab}"]');pg.wait_for_timeout(150)
        c=pg.locator('#md .cat-i').count();chk(f"{ab}: {k}",c==k,c)
    pg.click('#md [data-ab="operacional"]');pg.locator('#md .cat-i:has-text("Mochila militar")').click();pg.wait_for_timeout(400)
    chk("mochila militar dá +2 de carga",ev("curF().inv.items.some(i=>i.n=='Mochila militar'&&i.ef[0].a=='carga'&&i.ef[0].v==2&&i.esp==0)"))
    pg.click('[data-act="op-cat"]');pg.click('#md [data-ab="modificacao"]');pg.wait_for_timeout(200)
    pg.locator('#md .cat-i:has-text("Certeira")').click();pg.wait_for_timeout(400)
    chk("modificação abre a escolha do item",pg.locator('#md .cat-i:has-text("Katana")').count()==1)
    pg.locator('#md .cat-i:has-text("Katana")').click();pg.wait_for_timeout(400)
    chk("Certeira sobe a categoria e registra a modificação",ev("curF().inv.items.some(i=>i.n=='Katana'&&i.catg==2&&(i.mods||[]).some(m=>m.n=='Certeira'))"))
    pg.click('[data-act="op-cat"]');pg.click('#md [data-ab="modificacao"]');pg.wait_for_timeout(200)
    pg.locator('#md .cat-i:has-text("Silenciador")').click();pg.wait_for_timeout(300)
    chk("modificação sem item compatível avisa e não aplica",pg.locator('#md .cat-i:has-text("Katana")').count()==0 and ev("curF().inv.items.every(i=>!(i.mods||[]).some(m=>(m.n||m)=='Silenciador'))"))
    pg.click('#md [data-ab="outros"]');pg.wait_for_timeout(150)
    chk("extras do app (Celular, Lanterna…) continuam",pg.locator('#md .cat-i:has-text("Celular")').count()==1)
    pg.click('#md [data-x]')
    chk("sem erros",not pg.errs,pg.errs)
    b.close()
report()
